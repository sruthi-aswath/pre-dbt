CREATE TABLE SOURCES_ACC.SAP.CATEGORY 
CLONE SOURCES_PROD.SAP.CATEGORY;

CREATE TABLE TRANSFORM_ACC.SALES.CATEGORY_FILTERS 
AS
SELECT *,
CASE WHEN CATEGORY_NAME = 'Electronics' THEN 'E'
     ELSE 'C' END AS CATEGORY_ABB
FROM SOURCES_ACC.SAP.CATEGORY
;
SELECT *
FROM TRANSFORM_ACC.SALES.CATEGORY_FILTERS;
